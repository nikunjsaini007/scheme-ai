export function translate(lang: Lang, key: string): string {
  if (lang === "en") return key;
  return hi[key] ?? key;
}

export function useT() {
  const lang = useLang((s) => s.lang);
  const t = useCallback((key: string) => translate(lang, key), [lang]);
  return { t, lang };
}
